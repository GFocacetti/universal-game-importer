// 'auto', or the code of a language in LANGUAGES
export type LanguageChoice = string;

export async function initLanguage(): Promise<void> {
	try {
		steamLanguage = await SteamClient.Settings.GetCurrentLanguage();
	} catch {
		steamLanguage = 'english';
	}
	setLanguage('auto');
}

// "auto" follows Steam (English for a language UGI doesn't have); the others are the user's choice
export function setLanguage(choice: LanguageChoice | undefined) {
	current = (choice && choice !== 'auto' ? LANGUAGES.find((l) => l.code === choice) : LANGUAGES.find((l) => l.steam === steamLanguage)) ?? ENGLISH;
}

// The UI language: its tag ('it-IT'), and the language as a whole
export const uiLocale = () => current.tag;
export const uiLanguage = () => current;
// Arabic is written right to left: UGI's pages, windows and texts are laid out that way too
export const textDir = (): 'rtl' | 'ltr' => (current.code === 'ar' ? 'rtl' : 'ltr');

// "3 days ago", in the UI language
export function relativeTime(iso: string): string {
	const seconds = (Date.parse(iso) - Date.now()) / 1000;
	const rtf = new Intl.RelativeTimeFormat(current.tag, { numeric: 'auto' });
	const units: [Intl.RelativeTimeFormatUnit, number][] = [['day', 86400], ['hour', 3600], ['minute', 60]];
	for (const [unit, size] of units) {
		if (Math.abs(seconds) >= size) return rtf.format(Math.round(seconds / size), unit);
	}
	return rtf.format(0, 'minute');
}

// A key with a "#one" variant uses it when {n} is 1 ("1 game", not "1 games")
export function t(key: keyof Strings, params: Record<string, string | number> = {}): string {
	const one = `${key}#one` as keyof Strings;
	const strings = current.strings;
	const text = Number(params.n) === 1 && one in strings ? strings[one] : strings[key];
	return text.replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? ''));
}
