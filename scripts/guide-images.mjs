// Turns the step pictures in frontend/guides/ into frontend/guideImages.ts, so they ship inside the
// plugin's script. Run it again after changing a picture: node scripts/guide-images.mjs
import fs from 'node:fs';
import path from 'node:path';

const dir = path.join(import.meta.dirname, '..', 'frontend', 'guides');
const lines = fs
	.readdirSync(dir)
	.filter((f) => f.endsWith('.webp'))
	.sort()
	.map((f) => `\t'${f.slice(0, -5)}': 'data:image/webp;base64,${fs.readFileSync(path.join(dir, f)).toString('base64')}',`);

fs.writeFileSync(
	path.join(dir, '..', 'guideImages.ts'),
	`// Generated by scripts/guide-images.mjs from the pictures in guides/: do not edit by hand.\n` +
		`// Each site's steps, "sgdb-1" being SteamGridDB's first.\n` +
		`const guideImages: Record<string, string> = {\n${lines.join('\n')}\n};\n\nexport default guideImages;\n`,
);
console.log(`${lines.length} pictures`);
